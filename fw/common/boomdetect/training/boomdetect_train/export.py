"""Write models as the C headers the translation units under models/ include.

Three table formats, one per family the C knows how to run:

* MLP: scaler, one or two hidden ReLU layers, linear output - with one, the
  format models/mlp_model_data_v6.h already has.
* linear: scaler, weights, bias - models/svm_model_data_v3.h's format.
* GBT: a forest as flat node arrays. Each tree is a contiguous run of nodes;
  a node with feature 0xFF is a leaf and its value is added to the sum. Split
  nodes send x[feature] <= threshold left, which is scikit-learn's
  HistGradientBoosting convention (its thresholds are midpoints between
  training values, so equality is a non-event).

Every header also gets its parity vectors: PARITY_N windows of real features
and the decision Python computed for them in float32. The C test
model_parity_test reads those and holds the two implementations together.
"""

from __future__ import annotations

import zlib
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from boomdetect_train.features import (
    HYBRID_AUX_LAYOUT,
    LAYOUT_STATS_SPECTRAL_MOD2S4S,
    LAYOUTS,
    N_MOD,
    N_STATS_SPECTRAL,
    spec_layout,
)
from boomdetect_train.train import ScaledModel

PARITY_N = 16


def _c_float(v: float) -> str:
    """Shortest repr that round-trips through float32, with the f suffix."""
    f = float(np.float32(v))
    s = f"{f:.9g}"
    if "e" not in s and "." not in s and "inf" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def _c_float_short(v: float) -> str:
    """The shortest decimal that reads back as the same float32, with the f suffix, and NaN
    as math.h's NAN: for the big generated tables (network weights, wide vectors)."""
    f = np.float32(v)
    if np.isnan(f):
        return "NAN"
    a = np.format_float_positional(f, unique=True, trim="-")
    b = np.format_float_scientific(f, unique=True, trim="-")
    s = a if len(a) <= len(b) else b
    if "." not in s and "e" not in s:
        s += "."
    return s + "f"


def _chunks(tokens: list[str], per_line: int = 8, indent: str = "    ") -> list[str]:
    return [
        indent + ", ".join(tokens[i : i + per_line]) + "," for i in range(0, len(tokens), per_line)
    ]


def _c_array(
    name: str, ctype: str, values: np.ndarray, dims: tuple[int, ...], fmt, per_line: int = 0
) -> str:
    """`static const <ctype> name[d0][d1] = { ... };` with 8 floats or 16 integers per line
    (or `per_line`).

    A 2-D array gets one braced row per leading index: gcc's -Wmissing-braces
    (on under -Wall, fatal under -Werror) rejects a flat initializer for it.
    """
    arr = np.asarray(values)
    per_line = per_line or (8 if ctype == "float" else 16)
    dim_str = "".join(f"[{d}]" for d in dims)
    lines = [f"static const {ctype} {name}{dim_str} = {{"]
    if len(dims) == 2:
        for r in arr.reshape(dims):
            row = _chunks([fmt(v) for v in r], per_line, indent="      ")
            row[0] = "    { " + row[0].lstrip()
            row[-1] += " },"
            lines += row
    else:
        lines += _chunks([fmt(v) for v in arr.reshape(-1)], per_line)
    lines.append("};")
    return "\n".join(lines)


def _header(guard: str, title: str, provenance: list[str]) -> list[str]:
    lines = [
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "/*",
        f" * {title}",
        " *",
        " * GENERATED by fw/common/boomdetect/training (bdtrain export); do not edit.",
    ]
    for p in provenance:
        lines.append(f" * {p}")
    lines += [" */", "", "#include <stdint.h>", ""]
    return lines


@dataclass
class ParityVectors:
    features: np.ndarray  # (n, n_features_full) float32, the FULL layout vector
    expected: np.ndarray  # (n,) float32 decisions from the Python forward pass
    # Synthetic vectors: generated on both sides from synth_seed (synthetic_features), so
    # only the decisions are stored - a wide layout's real vectors cost kilobytes each.
    synth_expected: np.ndarray | None = None
    synth_seed: int = 0
    nan_a: tuple[int, int] = (0, 0)  # (start, length) set to NaN in synthetic vector k % 3 >= 1
    nan_b: tuple[int, int] = (0, 0)  # ... and this one too in k % 3 == 2


# Parity vectors of the wide layouts (the spectrogram networks and their pairs): a few
# real windows, the rest synthetic. A pair's network is checked by its own entry, so
# the pair needs one real window to prove the composition.
PARITY_N_WIDE = 2
PARITY_N_WIDE_PAIR = 1
PARITY_N_SYNTH = 8
SYNTH_SCALE = 3.0


def synthetic_features(
    width: int,
    seed: int,
    k: int,
    nan_a: tuple[int, int] = (0, 0),
    nan_b: tuple[int, int] = (0, 0),
) -> np.ndarray:
    """Synthetic vector k: uniform in [-3, 3) from a 32-bit LCG, the C's exact sequence.

    tests/model_parity_test.c generates the same numbers: the state update is integer
    arithmetic, v is a 24-bit integer (exact in float32), and v * 2^-23 * 3 rounds once
    in both languages. Vector k % 3 == 1 has the range nan_a set to NaN, k % 3 == 2 nan_a
    and nan_b - the shapes a hybrid's aux takes before the envelope ring is full.
    """
    mask = 0xFFFFFFFF
    state = (seed * 2654435761 + k * 40503 + 1) & mask
    out = np.empty(width, dtype=np.float32)
    unit = np.float32(1.0 / 8388608.0)
    scale = np.float32(SYNTH_SCALE)
    for i in range(width):
        state = (state * 1664525 + 1013904223) & mask
        v = ((state >> 8) & 0xFFFFFF) - 0x800000
        out[i] = np.float32(v) * unit * scale
    if k % 3 >= 1 and nan_a[1]:
        out[nan_a[0] : nan_a[0] + nan_a[1]] = np.nan
    if k % 3 == 2 and nan_b[1]:
        out[nan_b[0] : nan_b[0] + nan_b[1]] = np.nan
    return out


def synth_seed_of(name: str) -> int:
    return zlib.crc32(name.encode("utf-8")) & 0xFFFFFFFF


def mod_nan_ranges(layout: int) -> tuple[tuple[int, int], tuple[int, int]]:
    """Where a spectrogram hybrid's aux holds modulation sets that are NaN while the
    envelope ring fills: (the set that fills last, the one before it)."""
    spec = spec_layout(layout)
    if spec is None or spec[0] not in HYBRID_AUX_LAYOUT:
        return (0, 0), (0, 0)
    start = spec[2] * 64 + N_STATS_SPECTRAL
    if HYBRID_AUX_LAYOUT[spec[0]] == LAYOUT_STATS_SPECTRAL_MOD2S4S:
        return (start + N_MOD, N_MOD), (start, N_MOD)
    return (start, N_MOD), (0, 0)


def parity_vectors(
    model, x_full: np.ndarray, n: int = PARITY_N, seed: int = 7, allow_nan: bool = False
) -> ParityVectors:
    """Pick `n` real windows spread over the score range and score them in Python.

    Windows with a missing feature (layout 4 before its ring is full) are left
    out unless `allow_nan`: the board never hands those to a tree or an MLP, so
    the C has no fill to compare. The spectrogram networks and their pairs do
    take them (their fills are part of the model), so they keep them.
    """
    rng = np.random.default_rng(seed)
    x_full = np.asarray(x_full)
    if not allow_nan:
        x_full = x_full[np.isfinite(x_full).all(axis=1)]
    if x_full.shape[0] <= n:
        pick = np.arange(x_full.shape[0])
    elif n == 1:
        # The strongest window: for a pair that is above every val negative, where
        # its z table extrapolates.
        pick = np.asarray([int(np.argmax(model.score(x_full)))])
    else:
        scores = model.score(x_full)
        order = np.argsort(scores)
        # Quantiles of the score distribution plus a few random ones: the
        # extremes are where a saturating or overflowing implementation shows.
        q = order[np.linspace(0, order.size - 1, max(n - 4, 2)).astype(int)]
        r = rng.choice(order, size=n - q.size, replace=False)
        pick = np.unique(np.concatenate([q, r]))[:n]
    feats = np.asarray(x_full[pick], dtype=np.float32)
    return ParityVectors(feats, np.asarray(model.score(feats), dtype=np.float32).reshape(-1))


def wide_parity_vectors(model, name: str, x_full: np.ndarray) -> ParityVectors:
    """A spectrogram network's or a pair's vectors: PARITY_N_WIDE real windows (NaN kept)
    and PARITY_N_SYNTH synthetic ones, of which only the decisions are stored."""
    n_real = PARITY_N_WIDE_PAIR if getattr(model, "kind", "") == "pair" else PARITY_N_WIDE
    pv = parity_vectors(model, x_full, n=n_real, allow_nan=True)
    width = LAYOUTS[model.layout].n_features
    nan_a, nan_b = mod_nan_ranges(model.layout)
    seed = synth_seed_of(name)
    synth = np.stack(
        [synthetic_features(width, seed, k, nan_a, nan_b) for k in range(PARITY_N_SYNTH)]
    )
    pv.synth_expected = np.asarray(model.score(synth), dtype=np.float32).reshape(-1)
    pv.synth_seed = seed
    pv.nan_a, pv.nan_b = nan_a, nan_b
    return pv


def mlp_hidden_layers(model: ScaledModel) -> int:
    """How many hidden layers an MLP has; the C translation unit differs per count."""
    return len(model.model.coefs_) - 1


def export_mlp(model: ScaledModel, tag: str, provenance: list[str]) -> str:
    """One hidden layer: mlp_w2/MLP_B2 are the output. Two: mlp_w2/mlp_b2 are the
    second hidden layer and mlp_w3/MLP_B3 the output (MLP_HIDDEN2 marks the format)."""
    clf = model.model
    layers = mlp_hidden_layers(model)
    if layers not in (1, 2):
        raise ValueError(f"the C side takes one or two hidden layers, not {layers}")
    w1 = clf.coefs_[0].T.astype(np.float32)  # (hidden, inputs)
    b1 = clf.intercepts_[0].astype(np.float32)
    hidden, inputs = w1.shape
    guard = f"MLP_MODEL_DATA_{tag.upper()}_H"
    scaler = [
        _c_array("mlp_scaler_mean", "float", model.scaler_mean, (inputs,), _c_float),
        "",
        _c_array("mlp_scaler_inv_std", "float", model.scaler_inv_std, (inputs,), _c_float),
        "",
        _c_array("mlp_w1", "float", w1, (hidden, inputs), _c_float),
        "",
        _c_array("mlp_b1", "float", b1, (hidden,), _c_float),
        "",
    ]
    if layers == 1:
        w2 = clf.coefs_[1][:, 0].astype(np.float32)
        b2 = float(clf.intercepts_[1][0])
        title = f"MLP {tag}: {inputs} -> {hidden} -> 1, ReLU, logit output"
        lines = _header(guard, title, provenance)
        lines += [
            f"#define MLP_NUM_INPUTS {inputs}",
            f"#define MLP_HIDDEN {hidden}",
            f"#define MLP_B2 {_c_float(b2)}",
            "",
            *scaler,
            _c_array("mlp_w2", "float", w2, (hidden,), _c_float),
        ]
    else:
        w2 = clf.coefs_[1].T.astype(np.float32)  # (hidden2, hidden)
        b2 = clf.intercepts_[1].astype(np.float32)
        w3 = clf.coefs_[2][:, 0].astype(np.float32)
        b3 = float(clf.intercepts_[2][0])
        hidden2 = w2.shape[0]
        title = f"MLP {tag}: {inputs} -> {hidden} -> {hidden2} -> 1, ReLU, logit output"
        lines = _header(guard, title, provenance)
        lines += [
            f"#define MLP_NUM_INPUTS {inputs}",
            f"#define MLP_HIDDEN {hidden}",
            f"#define MLP_HIDDEN2 {hidden2}",
            f"#define MLP_B3 {_c_float(b3)}",
            "",
            *scaler,
            _c_array("mlp_w2", "float", w2, (hidden2, hidden), _c_float),
            "",
            _c_array("mlp_b2", "float", b2, (hidden2,), _c_float),
            "",
            _c_array("mlp_w3", "float", w3, (hidden2,), _c_float),
        ]
    lines += ["", f"#endif /* {guard} */", ""]
    return "\n".join(lines)


def export_linear(model: ScaledModel, tag: str, provenance: list[str]) -> str:
    clf = model.model
    w = clf.coef_[0].astype(np.float32)
    b = float(clf.intercept_[0])
    n = w.shape[0]
    guard = f"SVM_MODEL_DATA_{tag.upper()}_H"
    lines = _header(
        guard, f"Linear SVM {tag}: {n} standardised features, margin output", provenance
    )
    lines += [
        f"#define SVM_NUM_FEATURES {n}",
        f"#define SVM_BIAS {_c_float(b)}",
        "",
        _c_array("svm_scaler_mean", "float", model.scaler_mean, (n,), _c_float),
        "",
        _c_array("svm_scaler_inv_std", "float", model.scaler_inv_std, (n,), _c_float),
        "",
        _c_array("svm_weights", "float", w, (n,), _c_float),
        "",
        f"#endif /* {guard} */",
        "",
    ]
    return "\n".join(lines)


GBT_LEAF = 0xFF


def flatten_forest(clf) -> dict[str, np.ndarray]:
    """HistGradientBoosting's per-tree node records as flat arrays, trees back to back."""
    roots, feat, thr, left, right, value = [], [], [], [], [], []
    base = 0
    for predictors in clf._predictors:
        nodes = predictors[0].nodes
        roots.append(base)
        for nd in nodes:
            if nd["is_leaf"]:
                feat.append(GBT_LEAF)
                thr.append(0.0)
                left.append(0)
                right.append(0)
                value.append(float(nd["value"]))
            else:
                if nd["is_categorical"]:
                    raise ValueError("categorical splits are not exportable")
                feat.append(int(nd["feature_idx"]))
                thr.append(float(nd["num_threshold"]))
                left.append(int(nd["left"]) + base)
                right.append(int(nd["right"]) + base)
                value.append(0.0)
        base += len(nodes)
    return {
        "roots": np.asarray(roots, dtype=np.int64),
        "feature": np.asarray(feat, dtype=np.int64),
        "threshold": np.asarray(thr, dtype=np.float32),
        "left": np.asarray(left, dtype=np.int64),
        "right": np.asarray(right, dtype=np.int64),
        "value": np.asarray(value, dtype=np.float32),
        "baseline": np.float32(clf._baseline_prediction.reshape(-1)[0]),
    }


def forest_decision(flat: dict[str, np.ndarray], x: np.ndarray) -> np.ndarray:
    """Evaluate the flattened forest exactly as the C will, in float32."""
    x = np.atleast_2d(np.asarray(x, dtype=np.float32))
    out = np.full(x.shape[0], flat["baseline"], dtype=np.float32)
    for i in range(x.shape[0]):
        acc = np.float32(flat["baseline"])
        for root in flat["roots"]:
            n = int(root)
            while flat["feature"][n] != GBT_LEAF:
                f = int(flat["feature"][n])
                n = (
                    int(flat["left"][n])
                    if x[i, f] <= flat["threshold"][n]
                    else int(flat["right"][n])
                )
            acc = np.float32(acc + flat["value"][n])
        out[i] = acc
    return out


def export_gbt(model: ScaledModel, tag: str, provenance: list[str]) -> str:
    flat = flatten_forest(model.model)
    n_nodes = flat["feature"].shape[0]
    n_trees = flat["roots"].shape[0]
    n_feat = model.n_features
    if n_nodes >= 0xFFFF:
        raise ValueError("forest too large for uint16 node indices")
    guard = f"GBT_MODEL_DATA_{tag.upper()}_H"
    lines = _header(
        guard,
        f"Gradient-boosted trees {tag}: {n_trees} trees, {n_nodes} nodes, {n_feat} features, "
        "log-odds output",
        provenance,
    )
    lines += [
        f"#define GBT_NUM_FEATURES {n_feat}",
        f"#define GBT_NUM_TREES {n_trees}",
        f"#define GBT_NUM_NODES {n_nodes}",
        f"#define GBT_LEAF {GBT_LEAF}u",
        f"#define GBT_BASELINE {_c_float(float(flat['baseline']))}",
        "",
        _c_array("gbt_tree_root", "uint16_t", flat["roots"], (n_trees,), lambda v: f"{int(v)}u"),
        "",
        _c_array(
            "gbt_node_feature", "uint8_t", flat["feature"], (n_nodes,), lambda v: f"{int(v)}u"
        ),
        "",
        _c_array("gbt_node_threshold", "float", flat["threshold"], (n_nodes,), _c_float),
        "",
        _c_array("gbt_node_left", "uint16_t", flat["left"], (n_nodes,), lambda v: f"{int(v)}u"),
        "",
        _c_array("gbt_node_right", "uint16_t", flat["right"], (n_nodes,), lambda v: f"{int(v)}u"),
        "",
        _c_array("gbt_node_value", "float", flat["value"], (n_nodes,), _c_float),
        "",
        f"#endif /* {guard} */",
        "",
    ]
    return "\n".join(lines)


def export_model(model: ScaledModel, tag: str, provenance: list[str]) -> str:
    if model.kind == "mlp":
        return export_mlp(model, tag, provenance)
    if model.kind == "svm":
        return export_linear(model, tag, provenance)
    if model.kind == "gbt":
        return export_gbt(model, tag, provenance)
    raise ValueError(model.kind)


def export_parity_block(name: str, layout: int, offset: int, vectors: ParityVectors) -> str:
    """The C for one model's parity vectors: full-layout features and expected decisions."""
    n, width = vectors.features.shape
    assert width == LAYOUTS[layout].n_features
    ident = name.replace("-", "_")
    # A network's or a pair's few wide vectors (NaN kept) in short floats.
    wide = vectors.synth_expected is not None
    fmt, per_line = (_c_float_short, 16) if wide else (_c_float, 0)
    lines = [
        f"/* {name}: layout {layout} ({LAYOUTS[layout].name}), offset {offset} */",
        _c_array(f"parity_{ident}_features", "float", vectors.features, (n, width), fmt, per_line),
        _c_array(f"parity_{ident}_expected", "float", vectors.expected, (n,), _c_float),
    ]
    if vectors.synth_expected is not None:
        m = vectors.synth_expected.shape[0]
        lines.append(
            _c_array(f"parity_{ident}_synth", "float", vectors.synth_expected, (m,), _c_float)
        )
    return "\n".join(lines)


def export_parity_header(
    entries: list[tuple[str, int, int, ParityVectors]], provenance: list[str]
) -> str:
    """tests/vectors/parity_vectors.h: every model's vectors plus a table to iterate."""
    guard = "BOOMDETECT_PARITY_VECTORS_H"
    lines = _header(guard, "Python-versus-C parity vectors for every registered model", provenance)
    lines += [
        "#include <math.h> /* NAN: a hybrid network's aux before the envelope ring is full */",
        "",
        "typedef struct",
        "{",
        "    const char  *name;",
        "    uint16_t     layout_id;",
        "    uint16_t     n_features;   /* full layout width */",
        "    uint16_t     n_vectors;",
        "    const float *features;     /* n_vectors x n_features */",
        "    const float *expected;     /* n_vectors */",
        "    /* Synthetic vectors (training/boomdetect_train/export.py synthetic_features):",
        "       generated from synth_seed on both sides, only the decisions stored. */",
        "    uint16_t     n_synth;",
        "    uint32_t     synth_seed;",
        "    uint16_t     nan_a_start, nan_a_len; /* NaN in vector k when k % 3 >= 1 */",
        "    uint16_t     nan_b_start, nan_b_len; /* ... and here too when k % 3 == 2 */",
        "    const float *synth_expected; /* n_synth, or NULL */",
        "} parity_entry_t;",
        "",
    ]
    for name, layout, offset, vec in entries:
        lines += [export_parity_block(name, layout, offset, vec), ""]
    lines.append("static const parity_entry_t parity_entries[] = {")
    for name, layout, _offset, vec in entries:
        ident = name.replace("-", "_")
        n, width = vec.features.shape
        if vec.synth_expected is None:
            synth = "0u, 0u, 0u, 0u, 0u, 0u, NULL"
        else:
            synth = (
                f"{vec.synth_expected.shape[0]}u, {vec.synth_seed}u, "
                f"{vec.nan_a[0]}u, {vec.nan_a[1]}u, {vec.nan_b[0]}u, {vec.nan_b[1]}u, "
                f"parity_{ident}_synth"
            )
        lines.append(
            f'    {{ "{name}", {layout}u, {width}u, {n}u, &parity_{ident}_features[0][0], '
            f"parity_{ident}_expected, {synth} }},"
        )
    lines += ["};", "", f"#endif /* {guard} */", ""]
    return "\n".join(lines)


def write_text(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    return path

/**
 * @file lms_filter.h
 * @brief Fixed-point filtered-x LMS active-noise-control demo core.
 *
 * The demo models this ANC topology:
 *
 *   x[n] -> P(z) -> d[n]
 *   x[n] -> G(z) -> y[n] -> C(z) -> secondary[n]
 *   e[n] = d[n] - secondary[n]
 *   x_filtered[n] = C_hat(z) * x[n]
 *   g_i[n + 1] = g_i[n] + (mu / P[n]) * e[n] * x_filtered[n - i]
 *
 * The step uses a normalized (NLMS-style) learning rate: `mu` is divided by the
 * instantaneous filtered-x power `P[n] = eps + sum |x_filtered[n - i]|^2`, where
 * the sum runs over all taps and all reference/actuator channels. This makes the
 * effective step independent of the input level and of the number of channels,
 * so the same `mu` works for SISO and multi-channel configurations.
 *
 * `P(z)` is generated by the Python harness. `G(z)` is the adaptive FIR
 * controller in this C core. `C(z)` is a fixed demo secondary path in this C
 * core. `C_hat(z)` is a similar, non-identical secondary-path estimate used
 * only by the filtered-x adaptation branch.
 *
 * All FIRs use newest-sample-first tap order: tap `i` multiplies sample
 * `n - i`. Public samples and coefficients use signed Q15-like PCM
 * (`int16_t`) centered around zero. The core API does not allocate heap memory;
 * callers provide a state buffer sized by `fxlms_state_size()`.
 */


/*
 * Regularization floor for the normalized (NLMS-style) step size, expressed as
 * a per-(channel, tap) energy added to the filtered-x power in the update
 * denominator. It keeps the step finite when the reference is silent and is
 * negligible relative to the filtered-x power during normal operation.
 */
#ifndef CONFIG_FXLMS_NLMS_POWER_FLOOR
#define CONFIG_FXLMS_NLMS_POWER_FLOOR 256
#endif

#ifndef CONFIG_FXLMS_MAX_REFERENCES
#define CONFIG_FXLMS_MAX_REFERENCES 4
#endif


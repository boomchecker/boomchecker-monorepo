#!/usr/bin/env python3
"""Generate the LaTeX rows for the camera-ready results tables from the evaluation CSVs.

Table II: held-out robustness of the deployed classifier (arm 3, new dataset, 30/70
window), int8 metrics as mean +- std over 5 training x 5 noise seeds, with a float32
MCC column showing the same models before quantization. Rows clean..5 dB are the
trained range; 0 and -5 dB (note a) are stress levels beyond the validated trigger envelope.

Ablation table: int8 MCC per SNR for the three augmentation arms.

Writes the complete table environments into BEC/article/tables/ as auto-generated
.tex fragments that article_main.tex includes.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

SCRIPT_DIR = Path(__file__).resolve().parent
RETRAIN = SCRIPT_DIR.parent / "retraining"
R3 = RETRAIN / "retrain-waveform2" / "results-new"
TABLES_DIR = SCRIPT_DIR.parent / "article" / "tables"
HEADER = "% AUTO-GENERATED by BEC/scripts/generate_results_tables.py -- do not edit by hand\n"

ORDER = ["clean", "30 dB", "20 dB", "10 dB", "5 dB", "0 dB", "-5 dB"]
LABELS = {"clean": "Clean", "30 dB": "30", "20 dB": "20", "10 dB": "10",
          "5 dB": "5", "0 dB": "0$^{\\mathrm{a}}$", "-5 dB": "$-5^{\\mathrm{a}}$"}


def load_runs(dirpath: Path, prefix: str) -> pd.DataFrame:
    frames = []
    for ts in range(42, 47):
        for ns in range(42, 47):
            df = pd.read_csv(dirpath / f"{prefix}train{ts}_noise{ns}.csv")
            frames.append(df)
    d = pd.concat(frames)
    d["snr_db"] = d["snr_db"].astype(str).str.strip()
    return d


def ms(series: pd.Series, pct: bool = False, decimals: int = 3) -> str:
    m, s = series.mean(), series.std()
    if pct:
        return f"{100*m:.2f} $\\pm$ {100*s:.2f}"
    return f"{m:.{decimals}f} $\\pm$ {s:.{decimals}f}"


def main() -> None:
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    main_runs = load_runs(R3, "metrics_")
    low_runs = load_runs(R3, "lowsnr_")
    all_runs = pd.concat([main_runs, low_runs])

    rows = []
    for snr in ORDER:
        i8 = all_runs[(all_runs["mode"] == "PC int8") & (all_runs["snr_db"] == snr)]
        f32 = all_runs[(all_runs["mode"] == "PC float32") & (all_runs["snr_db"] == snr)]
        assert len(i8) == 25 and len(f32) == 25, (snr, len(i8), len(f32))
        rows.append(f"{LABELS[snr]} & {ms(i8['accuracy'], pct=True)} & {ms(i8['precision'])} & "
                    f"{ms(i8['recall'])} & {ms(i8['f1'])} & {ms(i8['mcc'])} & {ms(f32['mcc'])} \\\\")
        if snr == "5 dB":
            rows.append("\\midrule")
    table2 = HEADER + """\\begin{table}[!tbh]
\\caption{Held-out robustness of the deployed int8 classifier (mean $\\pm$ std over five training and five noise seeds).}
\\label{tab:robustness_heldout}
\\centering
\\resizebox{\\linewidth}{!}{%
\\begin{tabular}{@{}ccccccc@{}}
\\toprule
SNR (dB) & Accuracy (\\%) & Precision & Recall & F1-score & MCC & MCC (float32) \\\\
\\midrule
""" + "\n".join(rows) + """
\\bottomrule
\\end{tabular}
}
\\par\\vspace{4pt}
{\\footnotesize $^{\\mathrm{a}}$Beyond the trigger stage's validated 5~dB envelope (Section~\\ref{sec:pipeline}).}
\\end{table}
"""
    out2 = TABLES_DIR / "table_robustness.tex"
    out2.write_text(table2, encoding="utf-8")
    print(f"Wrote {out2}")

    arms = {
        "MFCC-domain jitter": RETRAIN / "retrain" / "results-new",
        "Jitter + waveform noise": RETRAIN / "retrain-waveform" / "results-new",
        "Waveform noise only": R3,
    }
    trained = ["clean", "30 dB", "20 dB", "10 dB", "5 dB"]
    arows = []
    for name, dirpath in arms.items():
        d = load_runs(dirpath, "metrics_")
        cells = []
        for snr in trained:
            sel = d[(d["mode"] == "PC int8") & (d["snr_db"] == snr)]["mcc"]
            assert len(sel) == 25
            cells.append(f"{sel.mean():.2f} $\\pm$ {sel.std():.2f}")
        arows.append(f"{name} & " + " & ".join(cells) + " \\\\")
    ablation = HEADER + """\\begin{table}[!tbh]
\\caption{Held-out int8 MCC (mean $\\pm$ std) for the same architecture trained with three augmentation strategies.}
\\label{tab:ablation_augmentation}
\\centering
\\resizebox{\\linewidth}{!}{%
\\begin{tabular}{@{}lccccc@{}}
\\toprule
Training augmentation & Clean & 30 dB & 20 dB & 10 dB & 5 dB \\\\
\\midrule
""" + "\n".join(arows) + """
\\bottomrule
\\end{tabular}
}
\\end{table}
"""
    out3 = TABLES_DIR / "table_ablation.tex"
    out3.write_text(ablation, encoding="utf-8")
    print(f"Wrote {out3}")


if __name__ == "__main__":
    main()
